export type Locale = 'en' | 'nl';
export const locales: Locale[] = ['en', 'nl'];

export function getLocale(currentLocale: string | undefined): Locale {
  return currentLocale === 'nl' ? 'nl' : 'en';
}

/** Map a pathname (including base) to its counterpart in the other locale. */
export function altPaths(pathname: string): { en: string; nl: string } {
  const base = import.meta.env.BASE_URL.replace(/\/$/, '');
  let rel = pathname.slice(base.length) || '/';
  if (!rel.startsWith('/')) rel = `/${rel}`;
  const isNl = rel === '/nl' || rel.startsWith('/nl/');
  const enRel = isNl ? rel.replace(/^\/nl/, '') || '/' : rel;
  const nlRel = isNl ? rel : `/nl${rel === '/' ? '/' : rel}`;
  return { en: `${base}${enRel}`, nl: `${base}${nlRel}` };
}

/** Locale-prefixed internal path (for use with url()). */
export function lpath(locale: Locale, path: string): string {
  const clean = path.replace(/^\//, '');
  return locale === 'nl' ? `nl/${clean}` : clean;
}

